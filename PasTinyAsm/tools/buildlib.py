#!/usr/bin/env python3
"""Assemble LIB.ASM into LIB.INC, the call library as Pascal constants.

  python3 tools/buildlib.py        (needs NASM)

Each routine is assembled alone at address 0, which also proves it does not
depend on where it is placed.  --check fails if LIB.INC is out of date.
"""
import re, subprocess, sys, tempfile
from pathlib import Path

root = Path(__file__).resolve().parents[1]


def routines():
    out, cur = [], None
    for line in (root / 'LIB.ASM').read_text().splitlines():
        m = re.match(r';; (\w+) (\d) (\d+) (\d+) (\d+) (\d+)$', line)
        if m:
            cur = dict(name=m[1], kind=int(m[2]), lim=[int(m[i]) for i in (3, 4, 5, 6)], src=[], doc='')
            out.append(cur)
        elif cur is not None:
            if line.startswith('; ') and not cur['src']:
                cur['doc'] += line[2:] + ' '
            cur['src'].append(line)
    return out


def assemble(src):
    with tempfile.TemporaryDirectory() as tmp:
        a, b = Path(tmp) / 'r.asm', Path(tmp) / 'r.bin'
        a.write_text('bits 16\ncpu 8086\norg 0\n' + '\n'.join(src) + '\n')
        subprocess.run(['nasm', '-f', 'bin', '-o', str(b), str(a)], check=True)
        return b.read_bytes()


def render():
    rs = routines()
    blob, rows = b'', []
    for r in rs:
        code = assemble(r['src'])
        rows.append("  (Name:'%s'; Kind:%d; Lo1:%d; Hi1:%d; Lo2:%d; Hi2:%d; Ofs:%d; Len:%d)"
                    % (r['name'], r['kind'], *r['lim'], len(blob), len(code)))
        blob += code
    lines = ['(* Generated by tools/buildlib.py from LIB.ASM.  Do not edit. *)',
             'const', ' LIBCOUNT=%d;' % len(rs), ' LIBSIZE=%d;' % len(blob),
             ' Lib:array[1..LIBCOUNT] of TCall=(', ',\n'.join(rows) + ');',
             ' LibCode:array[0..LIBSIZE-1] of Byte=(']
    hexs = ['$%02X' % c for c in blob]
    lines += ['  ' + ','.join(hexs[i:i + 16]) + (',' if i + 16 < len(hexs) else ');') for i in range(0, len(hexs), 16)]
    return '\n'.join(lines).replace('\n', '\r\n') + '\r\n', rs, blob


if __name__ == '__main__':
    text, rs, blob = render()
    path = root / 'LIB.INC'
    if '--check' in sys.argv:
        sys.exit(0 if path.read_text().split() == text.split() else 'LIB.INC is out of date')
    path.write_bytes(text.encode())
    print('%d routines, %d bytes' % (len(rs), len(blob)))
